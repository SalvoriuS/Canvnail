const { openInspector, openDrawing } = require('./helpers.cjs');
const { chromium, launchOptions, baseURL, isLocalRequest } = require('./browser-runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { readProject } = require('./helpers.cjs');

(async () => {
  const out = path.join(__dirname, 'artifacts');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch(launchOptions);
  require('./helpers.cjs').useDownloadFallback(browser);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  const rect = () => page.locator('#artboard [data-element-id]').first().boundingBox();
  const project = () => readProject(page);
  const waitSave = () => page.waitForFunction(() => document.querySelector('#save-state').textContent.includes('Guardado'));
  const set = async (label, value) => { await openInspector(page, ['Grosor','Padding horizontal','Padding vertical','Esquinas redondeadas'].includes(label) ? 'effects' : ['X','Y','Ancho de la caja'].includes(label) ? 'position' : 'content'); const field = page.getByRole('spinbutton', { name: label, exact: true }); await field.fill(String(value)); await field.press('Tab'); };
  try {
    await page.goto(baseURL);
    await page.getByRole('heading', { name: 'Tu página está vacía' }).waitFor();
    assert.equal(await page.locator('#artboard [data-element-id]').count(), 0);
    await page.screenshot({ path: path.join(out, '01-blank.png') });
    await page.getByRole('button', { name: 'Añadir texto', exact: true }).first().click();
    await page.getByRole('textbox', { name: 'Contenido del texto', exact: true }).fill('CREA A TU MANERA');
    await page.getByRole('textbox', { name: 'Contenido del texto', exact: true }).press('Tab');
    await set('Tamaño de fuente', 70);
    await set('Ancho de la caja', 820);
    await set('X', 200); await set('Y', 250);
    await waitSave();
    let state = await project();
    assert.equal(state.elements[0].fontFamily, 'Comic Sans MS');
    assert.equal(state.elements[0].outline, true); assert.equal(state.elements[0].background, true);
    assert.equal(await page.locator('#artboard text').getAttribute('stroke-width'), '4');
    assert.equal(await page.locator('#artboard [data-element-id] rect[rx]').count(), 1);
    await openInspector(page,'effects');
    await page.getByRole('textbox', { name: 'Color del fondo hexadecimal', exact: true }).fill('#a6c9ff');
    await page.getByRole('textbox', { name: 'Color del fondo hexadecimal', exact: true }).press('Tab');
    await set('Grosor', 7); await set('Padding horizontal', 35); await set('Esquinas redondeadas', 24);
    await page.screenshot({ path: path.join(out, '02-editor.png') });
    // Pointer drag in screen pixels must convert back to document coordinates.
    const before = await rect();
    await page.keyboard.down('Alt');
    await page.mouse.move(before.x + before.width / 2, before.y + before.height / 2);
    await page.mouse.down(); await page.mouse.move(before.x + before.width / 2 + 40, before.y + before.height / 2 + 25, { steps: 8 }); await page.mouse.up();
    await page.keyboard.up('Alt');
    const after = await rect();
    assert.ok(Math.abs(after.x - before.x - 40) < 1, 'drag x');
    assert.ok(Math.abs(after.y - before.y - 25) < 1, 'drag y');
    // Side handle reflows; corner handle scales the font and effects.
    await openInspector(page,'content');
    let fontSize = Number(await page.getByRole('spinbutton', { name: 'Tamaño de fuente', exact: true }).inputValue());
    const side = await page.locator('[data-handle="e"]').boundingBox();
    await page.mouse.move(side.x + side.width / 2, side.y + side.height / 2); await page.mouse.down(); await page.mouse.move(side.x + side.width / 2 + 30, side.y + side.height / 2, { steps: 5 }); await page.mouse.up();
    assert.equal(Number(await page.getByRole('spinbutton', { name: 'Tamaño de fuente', exact: true }).inputValue()), fontSize);
    const corner = await page.locator('[data-handle="se"]').boundingBox();
    await page.mouse.move(corner.x + corner.width / 2, corner.y + corner.height / 2); await page.mouse.down(); await page.mouse.move(corner.x + corner.width / 2 + 30, corner.y + corner.height / 2 + 10, { steps: 5 }); await page.mouse.up();
    assert.ok(Number(await page.getByRole('spinbutton', { name: 'Tamaño de fuente', exact: true }).inputValue()) > fontSize);
    // Duplication, order, visibility and lock must affect the same scene.
    await page.getByRole('button', { name: 'Duplicar texto', exact: true }).click();
    await waitSave();
    state = await project(); assert.equal(state.elements.length, 2);
    const copyId = state.elements[1].id;
    await page.getByRole('button', { name: 'Atrasar capa', exact: true }).click();
    await waitSave(); assert.equal((await project()).elements[0].id, copyId);
    await page.locator(`.layer-row[data-layer-id="${copyId}"]`).getByRole('button', { name: 'Ocultar capa', exact: true }).click();
    assert.equal(await page.locator('#artboard [data-element-id]').count(), 1);
    await page.locator(`.layer-row[data-layer-id="${copyId}"]`).getByRole('button', { name: 'Mostrar capa', exact: true }).click();
    await page.locator(`.layer-row[data-layer-id="${copyId}"]`).getByRole('button', { name: 'Bloquear capa', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Contenido del texto', exact: true }).isDisabled(), true);
    await page.getByRole('button', { name: 'Deshacer', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Contenido del texto', exact: true }).isDisabled(), false);
    await page.getByRole('button', { name: 'Rehacer', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: 'Contenido del texto', exact: true }).isDisabled(), true);
    await page.locator(`.layer-row[data-layer-id="${copyId}"]`).getByRole('button', { name: 'Desbloquear capa', exact: true }).click();
    // Layer drag changes stack order and keyboard movement respects document units.
    await page.locator(`.layer-row[data-layer-id="${copyId}"]`).dragTo(page.locator('.layer-row').first());
    await waitSave(); assert.equal((await project()).elements.at(-1).id, copyId);
    await page.locator(`.layer-row[data-layer-id="${copyId}"] .layer-select`).click();
    await waitSave();
    const keyX = (await project()).elements.find(e => e.id === copyId).x;
    await page.keyboard.press('Shift+ArrowRight');
    await waitSave(); assert.equal((await project()).elements.find(e => e.id === copyId).x, keyX + 10);
    // Local project download and a clean-browser import preserve all editable data.
    const save = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Guardar proyecto', exact: true }).click();
    const projectDownload = await save; const projectPath = path.join(out, 'roundtrip.trazo.json');
    await projectDownload.saveAs(projectPath);
    const saved = JSON.parse(await fs.readFile(projectPath, 'utf8'));
    const second = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const secondPage = await second.newPage(); await secondPage.goto(baseURL);
    await secondPage.locator('#project-file').setInputFiles(projectPath);
    await secondPage.waitForFunction(() => document.querySelectorAll('#artboard [data-element-id]').length === 2);
    await secondPage.waitForFunction(() => document.querySelector('#save-state').textContent.includes('Guardado'));
    assert.deepEqual(await readProject(secondPage), require('./helpers.cjs').legacyView(saved));
    await secondPage.reload(); await secondPage.locator('#artboard [data-element-id]').first().waitFor(); assert.equal(await secondPage.locator('#artboard [data-element-id]').count(), 2);
    const png = secondPage.waitForEvent('download'); await secondPage.getByRole('button', { name: 'Exportar PNG', exact: false }).click();
    const pngDownload = await png; const pngPath = path.join(out, 'export.png'); await pngDownload.saveAs(pngPath);
    const bytes = await fs.readFile(pngPath); assert.equal(bytes.toString('hex', 0, 8), '89504e470d0a1a0a');
    assert.equal(bytes.readUInt32BE(16), 1280); assert.equal(bytes.readUInt32BE(20), 720);
    if (await secondPage.getByRole('button', { name: 'Propiedades del lienzo', exact: true }).count()) await secondPage.getByRole('button', { name: 'Propiedades del lienzo', exact: true }).click();
    await secondPage.getByLabel('Formato del lienzo', { exact: true }).selectOption('vertical');
    assert.equal(await secondPage.locator('#artboard').getAttribute('viewBox'), '0 0 1080 1920');
    const widthField = secondPage.getByRole('spinbutton', { name: 'Ancho del lienzo', exact: true });
    await widthField.fill('1600'); await widthField.press('Tab');
    assert.equal(await secondPage.locator('#artboard').getAttribute('viewBox'), '0 0 1600 1920');
    assert.equal(await secondPage.getByLabel('Formato del lienzo', { exact: true }).inputValue(), 'custom');
    await secondPage.setViewportSize({ width: 390, height: 844 });
    await secondPage.screenshot({ path: path.join(out, '03-mobile.png'), fullPage: true });
    assert.ok(await secondPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile has no horizontal page overflow');
    await second.close();
    assert.deepEqual(errors, [], 'no browser errors');
    assert.ok(requests.every(url => url.startsWith(baseURL)), 'editor makes no external requests');
    console.log('PASS: blank canvas, text effects, pointer movement, side/corner resizing, layers, lock, undo/redo, project round trip, reload, PNG, vertical canvas, mobile layout, zero external requests.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
